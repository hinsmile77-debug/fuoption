"""완성봉 「늦은 틱 유예」의 단일 정본 — Horizon → 유예(ms) (2026-09-01 F-82).

## 왜 별도 모듈인가

이 정책은 2026-08-25 F-43 이후 `features/engine._grace_ms()` 안에 살았고, 거기서
`data/bar_composer`를 **함수 안에서** 들여왔다 — 그 모듈이 `ParquetArchiver`(polars)를
끌고 오기 때문이다. 그 회피는 엔진에서는 통했지만, 2026-09-01 F-82가 **화면**에도 같은
값을 요구하면서 깨졌다: `ui/app.py`는 polars를 이 프로세스에 들이지 않기로 한 자리다
(모듈 docstring — 2026-08-03 네이티브 크래시 5거래일 연속). 무거운 쪽을 안 들이면서
같은 값을 쓰려면 **정책이 무거운 모듈 밖에** 있어야 한다.

숫자를 화면에 다시 적는 선택지는 없다. 유예는 「넘으면 자료가 빠질 수 있는 경계」라
두 곳이 갈라지면 한쪽이 조용히 틀린 시각을 말하게 된다(L18).

## 값의 근거는 여기가 아니라 상류에 있다

1분봉은 정규화기가 늦은 틱을 받아 주는 창(`MINUTE_CLOSE_GRACE_SECONDS`), 상위 Horizon은
합성기가 마지막 구성 1분봉을 기다리는 상한(`MAX_CONSTITUENT_WAIT_SECONDS`)이 경계다.
후자는 2026-09-01에 `bar_composer`에서 이 모듈로 **옮겨 왔다**(값·근거 그대로) — 옮긴
이유는 위 무게 문제 하나뿐이고, `bar_composer`는 여기서 도로 읽는다.

**합성봉의 유예는 그 상한과 같은 값이 아니다** (2026-09-10 F-94). 상한은 합성기가
「언제까지 기다리는가」이고, 유예는 「넘으면 자료가 빠질 수 있는 경계」다. 발행 오프셋에는
스케줄러 위상과 계산 시간이 얹히므로 두 값을 같게 두면 유실 없이도 위반이 찍힌다 —
그래서 유예 = 상한 + `COMPOSED_GRACE_OVERHEAD_SECONDS`다. 상세 근거는 그 상수 주석에 있다.
"""

from __future__ import annotations

from messiah.core.messages import Horizon
from messiah.data.normalizer import MINUTE_CLOSE_GRACE_SECONDS

# 겹④ — 그 버킷의 마지막 1분봉이 도착하기를 기다리는 상한.
#
# 2026-08-05 실측 1분봉 발행 지연: 중앙값 0.655초 · p75 0.966초 · p90 1.62초 · 최대 7.96초
# (`data/bar_composer` 모듈 docstring "스큐를 고쳤더니 드러난 것"). 5초면 그날 표본의
# p99 위쪽을 덮는다 — **덮지 못했다. 2026-09-10에 5.0 → 10.0으로 올렸다(F-94).**
#
# ## 왜 5초가 모자랐나 (2026-09-10 실측, 14거래일 5,726건)
#
#     p50 0.29초 · p90 1.08초 · p99 3.06초 · p99.9 5.47초 · **최대 8.73초**
#
# 상한 초과 건수: 5초 10건(거래일당 0.71건) · 6초 3건 · 7초 3건 · 8초 1건 · **9초 0건**.
# 즉 5초는 p99.9(5.47초) 바로 아래에 있었고, 꼬리의 마지막 한 마디를 덮지 못했다.
#
# 39거래일 로그에서 실제 유실이 난 날은 4일이고 성격이 셋으로 갈린다:
#
#     08-05  103건  필요대기 0.51~2.90초  유실 0      겹①~③ 도입 전날 — 5초로 이미 막힌다
#     08-13    2건  필요대기 60.00초      유실 504    **장 마감 무거래 분 — 어떤 상한도 못 막는다**
#     08-14    1건  필요대기 8.69초       유실 129    진짜 늦은 봉
#     09-07    1건  필요대기 7.98초       유실 162    진짜 늦은 봉
#
# **상한으로 막을 수 있는 것은 뒤의 두 건이고 그 최댓값이 8.69초다.** 관측 최대 지연
# 8.73초와 사실상 같은 값이라 경험적 최악은 8.7초 근방으로 수렴한다. 10초는 그것을
# 15% 여유로 덮고, 9초 초과 관측이 0건이라 더 올릴 근거가 없다.
#
# 08-13형(마감 무렵 거래가 없어 봉 자체가 발행되지 않는 분)은 상한 문제가 아니다 —
# 오히려 상한을 키우면 그만큼 마감이 늦어진다. 별건으로 남긴다(`dev_memory/NEXT_TODO.md`).
#
# 상한을 이 크기로 둬도 안전한 이유: 가장 짧은 합성 Horizon이 3분(180초)이라 10초는 그 5.6%다
# (5초일 때 2.8%). 그리고 이 대기는 **유휴 시간**이다 — 대기를 걷어낸 순수 계산 시간은
# p99 479ms · 최대 602ms로(2026-08-24 실측 598건) 병목이 아니다.
# 대기의 최악은 "합성봉이 몇 초 늦게 나간다"인 반면, 안 기다린 최악은 **조용한 데이터
# 손상**이다 — 2026-08-05에 실제로 상위 봉의 3~17%가 그렇게 사라졌다. 비대칭이 명확하다.
MAX_CONSTITUENT_WAIT_SECONDS = 10.0

# 합성봉 유예에 얹는 **오버헤드 여유** (2026-09-10 F-94, 사용자 결정으로 신설).
#
# ## 왜 유예가 상한과 같은 값이면 안 되나
#
# 합성봉의 발행 오프셋은 구조적으로 `min(구성봉 지연, 상한) + 오버헤드`다. 오버헤드는
# 스케줄러 위상(`bar_composer._COMPOSE_SCHEDULER_PHASE_SECONDS` 0.5초)과 순수 계산
# 시간(p99 479ms · 최대 602ms)의 합이라 최대 1.1초가량이다.
#
# 그래서 유예를 상한과 **정확히 같은 값**으로 두면, 대기를 끝까지 쓴 날은 유실이 한 건도
# 없는데도 오버헤드만으로 유예를 넘는다. 실측으로 그런 것이 넷이다(상한 5.0초 시절):
#
#     3m 5.53초(08-21) · 5.79초(08-26) · 5.16초(08-31) · 5m 6.63초(09-07)
#
# 네 건 모두 `late_bar_drops`는 0이었다 — **고칠 것이 없는 곳으로 사람을 보내는 신호**이고,
# 그것이 `ui-restart-observability`가 2026-08-19에 맞은 형태와 같다(그 항목 주석 참조).
#
# 1.5초는 관측 오버헤드 최대(1.1초)에 여유를 얹은 값이다. 이 여유를 두면 유예 위반의 뜻이
# **「상한까지 기다렸는데 안 왔다」 = 유실 가능**으로 좁혀진다.
COMPOSED_GRACE_OVERHEAD_SECONDS = 1.5


def close_grace_ms(horizon: Horizon) -> float:
    """그 Horizon의 완성봉 유예(ms) — **「넘으면 손실인가」의 경계**다.

    `features/engine._PUBLISH_SLA_MS`(1,000ms)와 다른 질문이다. 저쪽은 「느린가」를 묻는
    채점 기준이고 이쪽은 경계다 — 2026-08-25에 1분봉 발행 오프셋 최대가 3,119.7ms였는데
    그날 자료 손실은 0건이었다. 두 값이 한 축에 섞여 있으면 그 사실을 말할 수 없다.
    """
    if horizon is Horizon.M1:
        return MINUTE_CLOSE_GRACE_SECONDS * 1000.0
    # 합성봉은 **상한 + 오버헤드 여유**다 — 같은 값으로 두면 유실 없이도 위반이 찍힌다
    # (`COMPOSED_GRACE_OVERHEAD_SECONDS` 주석의 실측 4건).
    return (MAX_CONSTITUENT_WAIT_SECONDS + COMPOSED_GRACE_OVERHEAD_SECONDS) * 1000.0
